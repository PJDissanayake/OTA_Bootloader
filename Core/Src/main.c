#include "main.h"
#include "xcp.h"
#include "spi.h"

#define APP_START_ADDR 0x08008000U

void SystemClock_Config(void);
static void MX_GPIO_Init(void);
static void MX_DMA_Init(void);


int main(void)
{

  HAL_Init();
  SystemClock_Config();
  MX_GPIO_Init();
  MX_DMA_Init();

  SPI_Init();
  SPI_Start();

  // Wait up to 5 seconds for master to connect
      uint32_t timeout = HAL_GetTick() + 5000;
      while (HAL_GetTick() < timeout) {
          if (xcp_connected) {
        	  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_7, GPIO_PIN_SET);
              // Master connected → stay in bootloader permanently
              while (1) {
                  HAL_Delay(500);
              }
          }
      }

      // Try to jump to application
      uint32_t app_stack = *(volatile uint32_t*)APP_START_ADDR;
      uint32_t app_entry = *(volatile uint32_t*)(APP_START_ADDR + 4);

      HAL_GPIO_WritePin(GPIOA, GPIO_PIN_7, GPIO_PIN_RESET);

      if ((app_stack > RAM_START) && (app_stack < (RAM_START + RAM_SIZE)) &&
          (app_entry > APP_START_ADDR) && (app_entry < FLASH_END))
      {
          typedef void (*pFunction)(void);
          pFunction JumpToApp = (pFunction)app_entry;

          __disable_irq();
          SCB->VTOR = APP_START_ADDR;
          __set_MSP(app_stack);
          JumpToApp();
      }



  while (1)
  {
	  HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_6);
	  HAL_Delay(200);
  }
}


